"""Deterministic, explicit owner-scoped notebook export (standard library only)."""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OWNERS = {
    "celal": ("notebooks/01_network_routing.ipynb", "routing_export", "src/citypilot/routing_engine.py"),
    "ali": ("notebooks/02_interventions_optimization.ipynb", "decision_export", "src/citypilot/decision_engine.py"),
}
HEADER = "# GENERATED by tools/export_notebooks.py; DO NOT HAND-EDIT.\n"


class ExportError(ValueError):
    """An export would violate notebook ownership or import safety."""


def _literal(node: ast.AST) -> bool:
    try:
        ast.literal_eval(node)
        return True
    except (ValueError, TypeError):
        return False


def _safe_module(source: str) -> None:
    """Reject executable top-level work and eager function/class expressions.

    C1 deliberately supports imports, function definitions and literal constants.
    Rich class definitions belong in the shared contracts module at this stage.
    """
    try:
        module = ast.parse(source)
    except SyntaxError as exc:
        raise ExportError(f"Exported code must be plain Python (no magics): {exc}") from exc
    for node in module.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            names = [n.name for n in node.names] if isinstance(node, ast.Import) else [node.module or ""]
            allowed = {"__future__", "pathlib", "typing", "math", "json", "hashlib", "time", "dataclasses", "collections", "citypilot.contracts"}
            if any(name not in allowed for name in names) or (isinstance(node, ast.ImportFrom) and node.level):
                raise ExportError("Import not in the C1 side-effect-free allowlist")
        elif isinstance(node, ast.ClassDef):
            raise ExportError("Shared classes belong in contracts.py; no local contract dialects")
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            defaults = [*node.args.defaults, *(v for v in node.args.kw_defaults if v is not None)]
            if node.decorator_list or any(not _literal(v) for v in defaults):
                raise ExportError("Function decorators and executable defaults are not import-safe")
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(not isinstance(t, ast.Name) for t in targets) or node.value is None or not _literal(node.value):
                raise ExportError("Only literal top-level constants are permitted")
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            pass
        else:
            raise ExportError(f"Top-level {type(node).__name__} is not import-safe")


# Owner "ali" (decision_export) only; owner "celal" keeps _safe_module unchanged.
DECISION_CLASSES = frozenset({
    "BaselineResult", "BaselineStep", "Candidate", "Co2Result", "DecisionProblem", "Limits",
    "ObjectiveModelMismatch", "OdCarDistance", "OptimizationResult", "PackageOutcome", "RemovalResult",
    "RequestContext", "ResourceResult", "Scenario", "ServiceResource", "StressFactorsNotSupported",
    "StressGrid", "StressPoint", "StressResult", "StressSetup",
})
DECISION_EXTRA_IMPORTS = frozenset({"csv", "itertools", "datetime", "yaml"})
DECISION_NONLITERAL_DEFAULT_FUNCTIONS = frozenset({"count_lost", "gate_objective"})


def _safe_decision_module(source: str) -> None:
    """Owner "ali": the decision allowlist above, then the shared rules for everything else."""
    try:
        module = ast.parse(source)
    except SyntaxError as exc:
        raise ExportError(f"Exported code must be plain Python (no magics): {exc}") from exc
    for node in module.body:
        if isinstance(node, ast.ClassDef) and node.name in DECISION_CLASSES:
            continue
        if isinstance(node, ast.Import) and {n.name for n in node.names} <= DECISION_EXTRA_IMPORTS:
            continue
        if (isinstance(node, ast.ImportFrom) and not node.level and node.module in DECISION_EXTRA_IMPORTS):
            continue
        if (isinstance(node, ast.FunctionDef) and node.name in DECISION_NONLITERAL_DEFAULT_FUNCTIONS
                and not node.decorator_list):
            continue
        _safe_module(ast.unparse(node))


def render(notebook: Path, owner: str, *, repo_root: Path = ROOT) -> tuple[Path, bytes]:
    if owner not in OWNERS:
        raise ExportError("Select exactly one owner: celal or ali")
    relative, tag, output = OWNERS[owner]
    root = repo_root.resolve()
    path = notebook if notebook.is_absolute() else root / notebook
    if path.resolve() != (root / relative).resolve():
        raise ExportError(f"Owner {owner} must explicitly select {relative}")
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ExportError(str(exc)) from exc
    chunks = []
    other_tag = "decision_export" if owner == "celal" else "routing_export"
    for cell in document.get("cells", []):
        tags = cell.get("metadata", {}).get("tags", [])
        if tag not in tags:
            continue
        if other_tag in tags or cell.get("cell_type") != "code":
            raise ExportError("Export tags must belong to one owner and a code cell")
        raw = cell.get("source", "")
        if not isinstance(raw, (str, list)) or (isinstance(raw, list) and any(not isinstance(v, str) for v in raw)):
            raise ExportError("Invalid cell source")
        source = (raw if isinstance(raw, str) else "".join(raw)).replace("\r\n", "\n").replace("\r", "\n").strip()
        if source:
            chunks.append(source)
    if not chunks:
        raise ExportError(f"No nonempty {tag} code cells found")
    # Hash only exported source, so outputs, execution counts and analysis do not affect it.
    body = "\n\n".join(chunks) + "\n"
    (_safe_decision_module if owner == "ali" else _safe_module)(body)
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    text = (HEADER + f"# Owner: {owner}; source: {relative}; tag: {tag}\n"
            + f"# Exported source SHA-256: {digest}\n"
            + "from __future__ import annotations\n\n" + body)
    try:
        compile(text, output, "exec")
    except SyntaxError as exc:
        raise ExportError(str(exc)) from exc
    destination = root / output
    if destination.resolve().parent != (root / "src/citypilot").resolve():
        raise ExportError("Generated target escapes package directory")
    if destination.is_symlink() or path.is_symlink():
        raise ExportError("Symlink input/output is not an owner-scoped export")
    return destination, text.encode("utf-8")


def export_notebook(notebook: Path, owner: str, *, repo_root: Path = ROOT, check: bool = False) -> Path:
    destination, expected = render(notebook, owner, repo_root=repo_root)
    if destination.exists():
        actual = destination.read_bytes()
        if actual == expected:
            return destination
        if not actual.startswith(HEADER.encode("utf-8")):
            raise ExportError("Refusing to overwrite a non-generated existing module")
    if check:
        raise ExportError("Generated module missing or stale")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(expected)
    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--owner", required=True, choices=tuple(OWNERS))
    parser.add_argument("--notebook", required=True, type=Path)
    parser.add_argument("--check", action="store_true", help="Check parity without writing")
    args = parser.parse_args()
    try:
        destination = export_notebook(args.notebook, args.owner, check=args.check)
    except ExportError as exc:
        parser.error(str(exc))
    print(destination.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
